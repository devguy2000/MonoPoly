#include "GameCodeGen.hpp"
#include <fstream>
#include <filesystem>

namespace fs = std::filesystem;

bool GameCodeGen::GenerateGame1(const std::string& projectPath,
                                 const std::string& projectName)
{
    fs::path game1Path = fs::path(projectPath) / "Game1.cs";

    std::ofstream f(game1Path.string(), std::ios::trunc);
    if (!f.is_open()) return false;

    // This Game1.cs reads Scene.mpscene at runtime so the MonoPoly editor
    // drives the game content without manual code changes.
    f << "// AUTO-GENERATED by MonoPoly IDE — extend freely, do not rename Game1.\n"
         "using Microsoft.Xna.Framework;\n"
         "using Microsoft.Xna.Framework.Graphics;\n"
         "using Microsoft.Xna.Framework.Input;\n"
         "using System.Collections.Generic;\n"
         "using System.IO;\n"
         "using System.Text.Json;\n"
         "\n"
         "namespace " << projectName << "\n"
         "{\n"
         "    internal sealed class SceneEntity\n"
         "    {\n"
         "        public string Name        { get; set; } = \"Entity\";\n"
         "        public float  X           { get; set; }\n"
         "        public float  Y           { get; set; }\n"
         "        public float  ScaleX      { get; set; } = 100f;\n"
         "        public float  ScaleY      { get; set; } = 100f;\n"
         "        public float  Rotation    { get; set; }\n"
         "        public string TextureName { get; set; } = \"\";\n"
         "        public float  R           { get; set; } = 1f;\n"
         "        public float  G           { get; set; } = 1f;\n"
         "        public float  B           { get; set; } = 1f;\n"
         "        public float  A           { get; set; } = 1f;\n"
         "    }\n"
         "\n"
         "    public class Game1 : Game\n"
         "    {\n"
         "        private GraphicsDeviceManager _graphics;\n"
         "        private SpriteBatch           _spriteBatch;\n"
         "        private readonly List<(SceneEntity entity, Texture2D tex)> _sprites = new();\n"
         "        private Texture2D _whitePixel;\n"
         "\n"
         "        public Game1()\n"
         "        {\n"
         "            _graphics = new GraphicsDeviceManager(this);\n"
         "            Content.RootDirectory = \"Content\";\n"
         "            IsMouseVisible        = true;\n"
         "            _graphics.PreferredBackBufferWidth  = 1280;\n"
         "            _graphics.PreferredBackBufferHeight = 720;\n"
         "        }\n"
         "\n"
         "        protected override void Initialize() => base.Initialize();\n"
         "\n"
         "        protected override void LoadContent()\n"
         "        {\n"
         "            _spriteBatch = new SpriteBatch(GraphicsDevice);\n"
         "            _whitePixel  = new Texture2D(GraphicsDevice, 1, 1);\n"
         "            _whitePixel.SetData(new[] { Color.White });\n"
         "            LoadScene(\"Scene.mpscene\");\n"
         "        }\n"
         "\n"
         "        private void LoadScene(string path)\n"
         "        {\n"
         "            if (!File.Exists(path)) return;\n"
         "            using var doc = JsonDocument.Parse(File.ReadAllText(path));\n"
         "            if (doc.RootElement.TryGetProperty(\"entities\", out var arr))\n"
         "                ParseEntities(arr);\n"
         "        }\n"
         "\n"
         "        private void ParseEntities(JsonElement arr)\n"
         "        {\n"
         "            foreach (var je in arr.EnumerateArray())\n"
         "            {\n"
         "                var e = new SceneEntity();\n"
         "                if (je.TryGetProperty(\"tag\",       out var t))  e.Name = t.GetString() ?? \"Entity\";\n"
         "                if (je.TryGetProperty(\"transform\", out var tf))\n"
         "                {\n"
         "                    if (tf.TryGetProperty(\"position\", out var p))\n"
         "                    { e.X = p.GetProperty(\"x\").GetSingle(); e.Y = p.GetProperty(\"y\").GetSingle(); }\n"
         "                    if (tf.TryGetProperty(\"scale\",    out var s))\n"
         "                    { e.ScaleX = s.GetProperty(\"x\").GetSingle(); e.ScaleY = s.GetProperty(\"y\").GetSingle(); }\n"
         "                    if (tf.TryGetProperty(\"rotation\", out var r)) e.Rotation = r.GetSingle();\n"
         "                }\n"
         "                Texture2D tex = _whitePixel;\n"
         "                if (je.TryGetProperty(\"sprite_renderer\", out var sr))\n"
         "                {\n"
         "                    if (sr.TryGetProperty(\"texture_path\", out var tp) && tp.GetString() is { Length: > 0 } name)\n"
         "                        try { tex = Content.Load<Texture2D>(name); } catch { }\n"
         "                    if (sr.TryGetProperty(\"color\", out var col))\n"
         "                    {\n"
         "                        e.R = col.GetProperty(\"r\").GetSingle(); e.G = col.GetProperty(\"g\").GetSingle();\n"
         "                        e.B = col.GetProperty(\"b\").GetSingle(); e.A = col.GetProperty(\"a\").GetSingle();\n"
         "                    }\n"
         "                    _sprites.Add((e, tex));\n"
         "                }\n"
         "                if (je.TryGetProperty(\"children\", out var ch)) ParseEntities(ch);\n"
         "            }\n"
         "        }\n"
         "\n"
         "        protected override void Update(GameTime gameTime)\n"
         "        {\n"
         "            if (GamePad.GetState(PlayerIndex.One).Buttons.Back == ButtonState.Pressed ||\n"
         "                Keyboard.GetState().IsKeyDown(Keys.Escape))\n"
         "                Exit();\n"
         "            // TODO: Add your update logic here\n"
         "            base.Update(gameTime);\n"
         "        }\n"
         "\n"
         "        protected override void Draw(GameTime gameTime)\n"
         "        {\n"
         "            GraphicsDevice.Clear(Color.Black);\n"
         "            _spriteBatch.Begin(samplerState: SamplerState.PointClamp);\n"
         "\n"
         "            int hw = GraphicsDevice.Viewport.Width  / 2;\n"
         "            int hh = GraphicsDevice.Viewport.Height / 2;\n"
         "\n"
         "            foreach (var (e, tex) in _sprites)\n"
         "            {\n"
         "                var color    = new Color(e.R, e.G, e.B, e.A);\n"
         "                var position = new Vector2(hw + e.X, hh - e.Y);  // Y-up → Y-down\n"
         "                var scale    = new Vector2(e.ScaleX / tex.Width, e.ScaleY / tex.Height);\n"
         "                var origin   = new Vector2(tex.Width * 0.5f, tex.Height * 0.5f);\n"
         "                _spriteBatch.Draw(tex, position, null, color, e.Rotation, origin, scale,\n"
         "                                  SpriteEffects.None, 0f);\n"
         "            }\n"
         "            _spriteBatch.End();\n"
         "\n"
         "            // TODO: Add your custom draw calls here\n"
         "            base.Draw(gameTime);\n"
         "        }\n"
         "    }\n"
         "}\n";

    return true;
}
